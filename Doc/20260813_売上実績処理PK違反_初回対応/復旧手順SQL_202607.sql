/*==================================================================================
  STEP4  復旧確認
==================================================================================*/
--  4-1  契約先NULLが解消されたか（0件になること）
SELECT  残存_契約先NULL = COUNT(*)
  FROM  売上実績テーブル
 WHERE  実績年月 = '202607' AND 契約先 IS NULL

--  4-2  契約先1048 の件数・金額（復旧前 14件 / 10,133,730円）
SELECT  契約先, 件数 = COUNT(*),
        金額計 = SUM(CONVERT(BIGINT, ISNULL(金額,0))),
        金額0件数 = SUM(CASE WHEN ISNULL(金額,0) = 0 THEN 1 ELSE 0 END)
  FROM  売上実績テーブル
 WHERE  実績年月 = '202607' AND 契約先 = '1048'
 GROUP BY 契約先

--  4-3  売上明細の欠落が解消されたか（入力区分='' が0件になること。'1'は手入力のため対象外）
SELECT  入力区分 = U.入力区分, 欠落件数 = COUNT(*)
  FROM  売上実績テーブル U
  LEFT  JOIN 売上明細テーブル M
    ON  M.検収管理NO = U.検収管理NO AND M.検収管理行NO = U.検収管理行NO AND M.実績年月 = U.実績年月
 WHERE  U.実績年月 = '202607' AND M.検収管理NO IS NULL
 GROUP BY U.入力区分

--  4-4  金額0の行が残っていないか（契約先別）
SELECT  契約先 = ISNULL(契約先,'(NULL)'),
        件数 = COUNT(*), 金額0件数 = SUM(CASE WHEN ISNULL(金額,0) = 0 THEN 1 ELSE 0 END)
  FROM  売上実績テーブル
 WHERE  実績年月 = '202607'
 GROUP BY ISNULL(契約先,'(NULL)')
HAVING  SUM(CASE WHEN ISNULL(金額,0) = 0 THEN 1 ELSE 0 END) > 0
 ORDER BY 1
GO

/*==================================================================================
  STEP5  再発防止チェック（★毎月の締め前に実行することを推奨）
          品番取引先マスタが引けない出荷が残っていないかを事前に洗い出す
==================================================================================*/
DECLARE @SD VARCHAR(8) = '20260801'   -- ★確認したい月の月初
DECLARE @ED VARCHAR(8) = '20260899'   -- ★確認したい月の月末

SELECT  KN.品番, 納入先 = KN.納入先, 受入 = KN.受入,
        出荷件数 = COUNT(*),
        出荷日MIN = MIN(JS.出荷日), 出荷日MAX = MAX(JS.出荷日)
  FROM  出荷テーブル JS
  JOIN  受注テーブル KN
    ON  KN.出荷指示書NO = JS.出荷指示書NO AND KN.出荷指示書行NO = JS.出荷指示書行NO
  LEFT  JOIN 品番取引先マスタ HT
    ON  HT.品番 = KN.品番 AND HT.取引先 = KN.納入先 AND HT.受入 = KN.受入
 WHERE  JS.出荷日 >= @SD AND JS.出荷日 <= @ED
   AND  ISNULL(KN.受注区分,0) <> 7
   AND  HT.品番 IS NULL                     -- ← 品番取引先マスタが引けない
 GROUP BY KN.品番, KN.納入先, KN.受入
 ORDER BY KN.納入先, KN.品番

--  5-2  契約先が空欄の品番取引先マスタ（登録はあるが契約先未設定＝同じ症状になる）
SELECT  品番, 取引先, 受入, 契約先, 作成日, 更新日
  FROM  品番取引先マスタ
 WHERE  ISNULL(RTRIM(契約先),'') = ''
 ORDER BY 取引先, 品番
GO
