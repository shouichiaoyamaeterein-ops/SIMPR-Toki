/**********************************************************************************
  売上実績処理 PK違反  復旧「前」確認SQL（残存リスクの潰し込み）

    作成日 : 2026/08/13
    対象DB : SIMTOKIDB

    ※ すべて参照系（SELECT）です。データの更新・削除は行いません。
    ※ 復旧手順SQL_202607.sql の STEP2 を実行する【前】に、本SQLで下記を確定させてください。

    ■ 目的
      報告書の記載のうち「未確認」として残っている点を潰し、
      復旧再処理で新たな事故（二重計上・別のPK違反）が起きないことを事前に確認する。
**********************************************************************************/
USE [SIMTOKIDB]
GO
SET NOCOUNT ON
GO

DECLARE @YM VARCHAR(6)  = '202607'
DECLARE @SD VARCHAR(8)  = '20260701'
DECLARE @ED VARCHAR(8)  = '20260799'

PRINT '========== ㉔ 契約先1048 の内訳（自動作成分と手入力分の切り分け）=========='
--  ㉓では 1048 は 14件 / 10,133,730円。うち何件が手入力(入力区分=1)かを確定する
--  自動作成分('')が極端に少ない場合、7月のアキタ向け売上がほぼ未計上の可能性がある
SELECT  入力区分 = ISNULL(入力区分,'(NULL)'),
        区分名 = CASE ISNULL(入力区分,'') WHEN ''  THEN '自動作成（売上実績作成）'
                                          WHEN '1' THEN '手入力'
                                          WHEN '2' THEN '型費'
                                          ELSE 'その他' END,
        件数 = COUNT(*),
        金額計 = SUM(CONVERT(BIGINT, ISNULL(金額,0))),
        締日MIN = MIN(CONVERT(SMALLINT, 締日)),
        締日MAX = MAX(CONVERT(SMALLINT, 締日)),
        作成日MIN = MIN(作成日),
        作成日MAX = MAX(作成日)
  FROM  売上実績テーブル
 WHERE  実績年月 = @YM AND 契約先 = '1048'
 GROUP BY ISNULL(入力区分,'(NULL)')
 ORDER BY 1

PRINT '========== ㉕【重要】当月の手入力行 19件の中身（応急手入力かどうかの判定）=========='
--  作成日が 2026-08-05 以降なら「処理が通らないので手入力で暫定計上した」可能性が高い
--  → その場合、復旧再処理で自動作成分が入ると【二重計上】になる
SELECT  検収管理NO, 検収管理行NO, 実績年月, 入力区分, 契約先, 納入先, 受入,
        品番, 納入番号, 検収年月日, 納入数, 単価, 金額, 締日,
        作成日, 作成端末, 作成者
  FROM  売上実績テーブル
 WHERE  実績年月 = @YM
   AND  ISNULL(入力区分,'') = '1'
 ORDER BY 契約先, 検収管理NO, 検収管理行NO

PRINT '========== ㉖【最重要】手入力行と当月出荷のキー衝突チェック（復旧前必須）=========='
--  手入力行(入力区分='1')は再処理のDELETEで削除されない（DELETE条件が 入力区分='' のため）。
--  その管理NOが当月出荷の 出荷指示書NO/行NO と一致すると、
--  残骸25件を消して再処理しても【別のPK違反】でまた止まる。
--  ここに行が返ったら、復旧前に個別の対応方針を決める必要がある。
SELECT  U.検収管理NO, U.検収管理行NO, U.実績年月, U.入力区分,
        手入力側契約先 = U.契約先, 手入力側品番 = U.品番, 手入力側金額 = U.金額,
        手入力側作成日 = U.作成日,
        出荷側出荷日 = JS.出荷日, 出荷側実績年月 = JS.実績年月,
        受注側品番 = KN.品番, 受注側納入先 = KN.納入先, 受注側受入 = KN.受入
  FROM  売上実績テーブル U
  JOIN  出荷テーブル JS
    ON  JS.出荷指示書NO   = U.検収管理NO
   AND  JS.出荷指示書行NO = U.検収管理行NO
  LEFT  JOIN 受注テーブル KN
    ON  KN.出荷指示書NO   = JS.出荷指示書NO
   AND  KN.出荷指示書行NO = JS.出荷指示書行NO
 WHERE  U.実績年月 = @YM
   AND  ISNULL(U.入力区分,'') <> ''          -- 再処理で消えない行
   AND  JS.出荷日 >= @SD AND JS.出荷日 <= @ED
 ORDER BY U.検収管理NO, U.検収管理行NO

PRINT '========== ㉗ 契約先1048 の自動作成分の締日分布（締日パラメータ決定の根拠）=========='
--  自動作成分('')に締日=0 の行があると、締日「個別31」で再処理した場合に
--  削除されずカーソルだけが拾い、再びPK違反になる。
--  ここが 31 だけなら「個別31」でも可。0 が混在するなら「全て」必須。
SELECT  締日 = ISNULL(CONVERT(SMALLINT, 締日), -999),
        入力区分 = ISNULL(入力区分,'(NULL)'),
        件数 = COUNT(*)
  FROM  売上実績テーブル
 WHERE  実績年月 = @YM AND 契約先 = '1048'
 GROUP BY ISNULL(CONVERT(SMALLINT, 締日), -999), ISNULL(入力区分,'(NULL)')
 ORDER BY 1, 2

PRINT '========== ㉘ 売上明細が欠落している4件の特定（欠落メカニズムの裏取り）=========='
--  報告書では「再処理のたびに明細の契約先が1048に更新され、次回DELETEで明細だけ消える」
--  と説明している。欠落4件が契約先NULLの25件に含まれるかで、この説明が裏取りできる。
SELECT  U.検収管理NO, U.検収管理行NO, U.実績年月, U.入力区分,
        契約先 = ISNULL(U.契約先,'(NULL)'),
        U.品番, U.納入先, U.受入, U.納入番号, U.検収年月日,
        U.納入数, U.単価, U.金額, U.作成日, U.作成端末
  FROM  売上実績テーブル U
  LEFT  JOIN 売上明細テーブル M
    ON  M.検収管理NO = U.検収管理NO AND M.検収管理行NO = U.検収管理行NO AND M.実績年月 = U.実績年月
 WHERE  U.実績年月 = @YM
   AND  ISNULL(U.入力区分,'') = ''
   AND  M.検収管理NO IS NULL
 ORDER BY U.検収管理NO, U.検収管理行NO

PRINT '========== ㉙ 対象5品番すべての品番取引先マスタ登録状況（⑰は1品番のみ確認だった）=========='
SELECT  品番, 取引先, 受入, 契約先, 納入先, 納入先受入, 品目,
        有効期限開始, 有効期限終了, 作成日, 更新日
  FROM  品番取引先マスタ
 WHERE  品番 IN ('6143190K00','6143290K00','5766360041','5559860010','6195636040')
 ORDER BY 品番, 取引先, 受入

PRINT '========== ㉙-2 5品番×納入先1048×受入01 の登録有無サマリ =========='
SELECT  品番 = X.品番,
        登録有無 = CASE WHEN HT.品番 IS NULL THEN '★未登録' ELSE '登録あり' END,
        契約先 = HT.契約先,
        マスタ作成日 = HT.作成日
  FROM  (SELECT '6143190K00' AS 品番 UNION ALL SELECT '6143290K00'
         UNION ALL SELECT '5766360041' UNION ALL SELECT '5559860010'
         UNION ALL SELECT '6195636040') X
  LEFT  JOIN 品番取引先マスタ HT
    ON  HT.品番 = X.品番 AND HT.取引先 = '1048' AND HT.受入 = '01'
 ORDER BY X.品番

PRINT '========== ㉚ 復旧後の想定件数・金額（事前試算）=========='
--  契約先NULL 25件が正しく計上された場合の金額（計算単位=1:切上げ）
SELECT  対象件数 = COUNT(*),
        単純合計 = SUM(納入数 * 単価),
        行別切上合計 = SUM(CEILING(納入数 * 単価))
  FROM  売上実績テーブル
 WHERE  実績年月 = @YM AND 契約先 IS NULL

--  伝票単位集計で行がまとまらないことの確認（まとまるなら件数が減る）
SELECT  品番, 納入番号, 検収年月日, 単価, 行数 = COUNT(*)
  FROM  売上実績テーブル
 WHERE  実績年月 = @YM AND 契約先 IS NULL
 GROUP BY 品番, 納入番号, 検収年月日, 単価
HAVING  COUNT(*) > 1
 ORDER BY 品番, 納入番号

PRINT '========== ㉛ 当月出荷でマスタが引けない組合せが他に残っていないか =========='
SELECT  KN.品番, 納入先 = KN.納入先, 受入 = KN.受入,
        出荷件数 = COUNT(*),
        出荷日MIN = MIN(JS.出荷日), 出荷日MAX = MAX(JS.出荷日)
  FROM  出荷テーブル JS
  JOIN  受注テーブル KN
    ON  KN.出荷指示書NO = JS.出荷指示書NO AND KN.出荷指示書行NO = JS.出荷指示書行NO
  LEFT  JOIN 品番取引先マスタ HT
    ON  HT.品番 = KN.品番 AND HT.取引先 = KN.納入先 AND HT.受入 = KN.受入
 WHERE  JS.出荷日 >= @SD AND JS.出荷日 <= @ED
   AND  ISNULL(KN.受注区分,0) <> 7
   AND  HT.品番 IS NULL
 GROUP BY KN.品番, KN.納入先, KN.受入
 ORDER BY KN.納入先, KN.品番
GO
